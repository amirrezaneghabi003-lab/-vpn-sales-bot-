def plan_volume(plan):
    name = str(plan.get('display', ''))
    size_gb = float(plan.get('size', 0))/1024
    if 'نامحدود' in name or 'نامحدود' in str(plan.get('type','')):
        return 'نامحدود (مصرف منصفانه: 100 گیگابایت)'
    return f'{size_gb:g} گیگابایت'


def customer_announcement(message):
    """Never advertise deprecated, unrelated services to VPN customers."""
    if not message:
        return None
    old_services = ('طراحی وبسایت', 'طراحی وب‌سایت', 'ساخت ربات', 'شماره مجازی',
                    'نمایندگی فروش سرور', 'کدنویسی اختصاصی', 'خدمات جدیدی که به ربات')
    return None if any(term in message for term in old_services) else message


