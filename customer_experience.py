def latin_digits(value):
    return str(value).translate(str.maketrans('۰۱۲۳۴۵۶۷۸۹٠١٢٣٤٥٦٧٨٩', '01234567890123456789'))


def fa_digits(value):
    return str(value).translate(str.maketrans('0123456789', '۰۱۲۳۴۵۶۷۸۹'))


def _jalali(y, m, d):
    """Convert civil Gregorian date to Jalali date, for supported modern years."""
    gy = y - 1600
    gm = m - 1
    gd = d - 1
    months = (31, 28, 31, 30, 31, 30, 31, 31, 30, 31, 30, 31)
    total = 365*gy + (gy+3)//4 - (gy+99)//100 + (gy+399)//400
    for idx in range(gm):
        total += months[idx]
    if gm > 1 and ((gy%4 == 0 and gy%100 != 0) or gy%400 == 0):
        total += 1
    total += gd
    jdays = total - 79
    cycles = jdays // 12053
    jdays %= 12053
    jy = 979 + 33*cycles + 4*(jdays//1461)
    jdays %= 1461
    if jdays >= 366:
        jy += (jdays - 1)//365
        jdays = (jdays - 1)%365
    if jdays < 186:
        jm = 1 + jdays//31
        jd = 1 + jdays%31
    else:
        jm = 7 + (jdays - 186)//30
        jd = 1 + (jdays - 186)%30
    return jy,jm,jd


def jalali_datetime(sqlite_timestamp):
    """UTC SQLite or offset-aware ISO timestamps -> Tehran wall-clock, Jalali date.

    SQLite CURRENT_TIMESTAMP is UTC, even if the host computer runs in Iran.
    An explicit ISO offset is honored; naive timestamps are treated as UTC.
    """
    if not sqlite_timestamp:
        return 'نامشخص'
    try:
        if isinstance(sqlite_timestamp, datetime):
            dt = sqlite_timestamp
        else:
            dt = datetime.fromisoformat(str(sqlite_timestamp).replace('Z', '+00:00'))
        if dt.tzinfo is None:
            dt = dt.replace(tzinfo=timezone.utc)
        dt = dt.astimezone(TEHRAN)
        y,m,d = _jalali(dt.year, dt.month, dt.day)
        return latin_digits(f'{y:04d}/{m:02d}/{d:02d} | {dt.hour:02d}:{dt.minute:02d} (تهران)')
    except (TypeError, ValueError, OverflowError):
        return 'نامشخص'


def money(value):
    return f'{int(value):,}'


def ensure_payment_schema(conn: sqlite3.Connection):
    conn.execute('''CREATE TABLE IF NOT EXISTS payment_rotation (
        id INTEGER PRIMARY KEY CHECK(id = 1),
        approval_count INTEGER NOT NULL DEFAULT 0 CHECK(approval_count >= 0)
    )''')
    conn.execute('INSERT OR IGNORE INTO payment_rotation(id,approval_count) VALUES(1,0)')
    for table in ('orders', 'tg_orders'):
        exists = conn.execute("SELECT 1 FROM sqlite_master WHERE type='table' AND name=?", (table,)).fetchone()
        if exists:
            columns = {r[1] for r in conn.execute(f'PRAGMA table_info({table})')}
            if 'payment_card_index' not in columns:
                conn.execute(f'ALTER TABLE {table} ADD COLUMN payment_card_index INTEGER')


def current_card_index(conn):
    row = conn.execute('SELECT approval_count FROM payment_rotation WHERE id=1').fetchone()
    if row is None:
        raise RuntimeError('Payment schema not initialized')
    return 1 + int(row[0]) % 2


def record_successful_approval(conn):
    conn.execute('UPDATE payment_rotation SET approval_count=approval_count+1 WHERE id=1')


